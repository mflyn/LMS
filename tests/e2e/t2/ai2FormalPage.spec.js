const { test, expect } = require('@playwright/test');
const { createAi2Fixture, login, publish, openPackage, upload, submit, viewImage, observe, capture, expectData } = require('./ai2Fixture');
let runtime;
test.beforeEach(async () => { runtime = await createAi2Fixture(); });
test.afterEach(async () => { await runtime?.stop(); runtime = null; });

test('AI2 formal page publish, revise, resubmit, approve, readback, privacy deletion and withdrawal', async ({ page, browser }, info) => {
  const seen = await observe(page, runtime), packageId = await publish(page, runtime);
  const context = await browser.newContext({ viewport: { width: 768, height: 1024 }, hasTouch: true });
  const child = await context.newPage(), childSeen = await observe(child, runtime);
  try {
    await login(child, runtime, 'child');
    await child.getByRole('link', { name: '我的学习包', exact: true }).click();
    await child.getByRole('link', { name: '查看学习包内容', exact: true }).click();
    await expect(child.getByRole('region', { name: '学习包详情', exact: true })).toBeVisible();
    await expect(child.getByText('PRIVATE_AI2_ANSWER')).toHaveCount(0);
    await expect(child.getByText('PRIVATE_AI2_CONTEXT')).toHaveCount(0);
    await expect(child.getByRole('button', { name: '提交订正', exact: true })).toBeDisabled();
    await upload(child, runtime); await submit(child);
    await child.reload(); await viewImage(child);
    await openPackage(page, runtime, packageId);
    await expect(page.getByRole('button', { name: '通过所见订正', exact: true })).toBeDisabled();
    await viewImage(page);
    await page.getByLabel('审核反馈', { exact: true }).fill('Please align the tens row.');
    await page.getByRole('button', { name: '退回再订正', exact: true }).click();
    await expect(page.getByRole('link', { name: '查看学习包', exact: true })).toBeVisible();
    await child.reload();
    await expect(child.getByRole('heading', { name: '请再订正', exact: true })).toBeVisible();
    await expect(child.getByText(/家长反馈：请再订正 Please align/)).toBeVisible();
    await upload(child, runtime, 'synthetic-second.png'); await submit(child, 'Aligned tens row.');
    await page.reload(); await viewImage(page);
    await page.getByLabel('审核反馈', { exact: true }).fill('The counting units now align.');
    await page.getByRole('button', { name: '通过所见订正', exact: true }).click();
    await expect(page.getByRole('link', { name: '查看学习包', exact: true })).toBeVisible();
    await page.getByRole('link', { name: '查看学习包', exact: true }).click();
    await expect(page.getByRole('heading', { name: '已通过', exact: true })).toBeVisible();
    await child.reload(); await viewImage(child);
    await expect(child.getByText(/家长反馈：通过 The counting units/)).toBeVisible();
    await expect(child.getByRole('button', { name: '提交订正', exact: true })).toBeDisabled();
    await capture(child, info, 'child-approved-ipad.png');
    await child.setViewportSize({ width: 390, height: 844 }); await capture(child, info, 'child-approved-mobile.png');
    await capture(page, info, 'parent-approved-desktop.png');
    await child.getByRole('button', { name: '查看订正历史', exact: true }).click();
    await child.getByRole('button', { name: '查看第 1 次订正', exact: true }).click();
    await expect(child.getByRole('heading', { name: '历史订正 · 第 1 次', exact: true })).toBeVisible();
    await expect(child.getByText(/家长反馈：请再订正 Please align/)).toBeVisible();
    const before = expectData(await runtime.parent.get(`/api/ai2/learning-packages/${packageId}`)).package;
    const mediaId = before.attempts[0].media[0].mediaId;
    const current = child.getByRole('article').filter({ has: child.getByRole('heading', { name: /当前订正/ }) });
    await current.getByRole('button', { name: '隐私删除订正图片 1', exact: true }).click();
    await child.getByRole('button', { name: '确认隐私删除', exact: true }).click();
    await expect(current.getByText('图片已隐私删除', { exact: true })).toBeVisible();
    await child.reload();
    await expect(child.getByText('图片已隐私删除', { exact: true })).toBeVisible();
    const after = expectData(await runtime.parent.get(`/api/ai2/learning-packages/${packageId}`)).package;
    expect(after.learningState).toBe('approved'); expect(after.stateVersion).toBe(before.stateVersion);
    expect(after.attempts[0].review).toEqual(before.attempts[0].review);
    expect(after.attempts[0].media).toEqual([expect.objectContaining({ mediaId, status: 'deleted' })]);
    await page.getByLabel('撤回原因', { exact: true }).fill('Synthetic end of exercise.');
    await page.getByRole('button', { name: '撤回学习包', exact: true }).click();
    await expect(page.getByRole('link', { name: '查看学习包', exact: true })).toBeVisible();
    await child.reload();
    await expect(child.getByText('当前身份无法查看这些私有学习内容。', { exact: true })).toBeVisible();
    await expect(child.getByRole('region', { name: '学习包详情', exact: true })).toHaveCount(0);
    expect(seen.errors).toEqual([]); expect(childSeen.errors).toEqual([]);
    expect(seen.external).toEqual([]); expect(childSeen.external).toEqual([]);
    expect(seen.console).toEqual([]);
    expect(childSeen.console.every(line => /404/.test(line))).toBe(true);
    await runtime.unchanged();
  } finally { await context.close(); }
});
